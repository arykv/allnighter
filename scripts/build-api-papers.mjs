/*
 * Emits `api/_papers.js` from `src/data/papers.ts`.
 *
 * ## Why this exists
 *
 * `api/plan.ts` has to validate the slug and unit numbers it is sent, and to do
 * that it needs the paper data. Importing `../src/data/papers` straight from the
 * function *typechecks and builds locally and then fails in production*: Vercel
 * transpiles `api/plan.ts` to `api/plan.js` but does not emit anything it
 * imports from outside `api/`, so the deployed function dies at cold start with
 *
 *     ERR_MODULE_NOT_FOUND  /var/task/src/data/papers
 *
 * Copying the data into `api/` by hand would fix it and break the rule that
 * matters more — weightage lives in exactly one place, or two copies drift and
 * one of them is a lie a student plans their night around.
 *
 * So: one source, generated. The output is plain `.js` rather than `.ts` on
 * purpose, so nothing has to compile it and there is no ordering question about
 * when Vercel collects the function.
 *
 * The result is committed. Generating it during the build covers Vercel, and
 * committing it covers the case where functions are collected before the build
 * command runs — cheap insurance against a failure mode that only appears in
 * production.
 */

import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { createServer } from 'vite'

const OUT = join(process.cwd(), 'api', '_papers.js')

const server = await createServer({
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'silent',
})

try {
  const { PAPERS } = await server.ssrLoadModule('/src/data/papers.ts')

  // Only what the function actually needs to validate a request and write a
  // prompt. Nothing here is rendered to a student by the API.
  const slim = PAPERS.map((p) => ({
    slug: p.slug,
    subject: p.subject,
    code: p.code,
    grade: p.grade,
    theoryMarks: p.theoryMarks,
    internalMarks: p.internalMarks,
    units: p.units.map((u) => ({ n: u.n, name: u.name, marks: u.marks, asked: u.asked })),
  }))

  const body = `// GENERATED by scripts/build-api-papers.mjs — do not edit.
// Source of truth is src/data/papers.ts. See that script's header for why this
// file exists at all rather than the function importing papers.ts directly.

export const PAPERS = ${JSON.stringify(slim, null, 2)}

export const paperBySlug = (slug) => PAPERS.find((p) => p.slug === slug)
`

  const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  writeFileSync(OUT, body)
  console.log(
    `api/_papers.js ${previous === body ? 'unchanged' : 'regenerated'} — ${slim.length} papers`,
  )
} finally {
  await server.close()
}
